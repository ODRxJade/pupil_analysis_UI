export const PARAM_LABELS: Partial<Record<keyof InferenceConfig, string>> = {
  dlcConfigPath: "DeepLabCut config path",
  snapshot: "Model snapshot",
  account: "Project / account",
  partition: "Partition",
  gpuType: "GPU type",
  condaEnv: "Conda environment",
  workDir: "Working directory",
  inputPath: "Input footage path",
  outputDir: "Output directory",
}

const ph = (value: string, placeholder: string) => (value.trim() ? value.trim() : `<${placeholder}>`)

export function slug(value: string) {
  return value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "")
    .slice(0, 24)
}

export function generateScript(
  cfg: InferenceConfig,
  template: SlurmTemplate,
  experiment: Experiment | undefined,
  session: Session | undefined,
): string {
  const gpu = template.id !== "dlc-cpu"
  const lines = [
    "#!/bin/bash",
    `# Pupil Dynamics — ${template.name} (template v${template.version})`,
    `# Experiment: ${experiment?.name ?? "<experiment>"} | Session: ${session?.label ?? "<session>"}`,
    `# Generated by Pupil Dynamics. Cluster-specific values must be confirmed for your allocation.`,
    "",
    `#SBATCH --job-name=pd-${slug(experiment?.name ?? "experiment")}-${(session?.label ?? "s").toLowerCase()}`,
    `#SBATCH --account=${ph(cfg.account, "PROJECT_ACCOUNT")}`,
    `#SBATCH --partition=${ph(cfg.partition, "PARTITION")}`,
  ]
  if (gpu) lines.push(`#SBATCH --gres=gpu:${ph(cfg.gpuType, "GPU_TYPE")}:${cfg.gpuCount}`)
  lines.push(
    `#SBATCH --cpus-per-task=${cfg.cpus}`,
    `#SBATCH --mem=${cfg.memoryGb}G`,
    `#SBATCH --time=${cfg.wallTime || "<HH:MM:SS>"}`,
    `#SBATCH --output=${ph(cfg.outputDir, "OUTPUT_DIR")}/slurm-%j.out`,
    `#SBATCH --error=${ph(cfg.outputDir, "OUTPUT_DIR")}/slurm-%j.err`,
  )
  if (cfg.email.trim()) lines.push(`#SBATCH --mail-user=${cfg.email.trim()}`, "#SBATCH --mail-type=END,FAIL")
  lines.push(
    "",
    "set -euo pipefail",
    "",
    "# Load your site's conda module here if required, e.g. module load <conda-module>",
    `source activate ${ph(cfg.condaEnv, "CONDA_ENV")}`,
    `cd ${ph(cfg.workDir, "WORK_DIR")}`,
    "",
    `export PD_INPUT="${ph(cfg.inputPath, "INPUT_PATH")}"`,
    `export PD_OUTPUT="${ph(cfg.outputDir, "OUTPUT_DIR")}"`,
    `export PD_LIKELIHOOD=${cfg.likelihoodThreshold}`,
    `mkdir -p "$PD_OUTPUT"`,
    "",
    `echo "[pd] Starting DeepLabCut inference ($SLURM_JOB_ID)"`,
    "python - <<'PY'",
    "import os",
    "import deeplabcut",
    "",
    "deeplabcut.analyze_videos(",
    `    "${ph(cfg.dlcConfigPath, "DLC_CONFIG_PATH")}",`,
    `    [os.environ["PD_INPUT"]],`,
    `    batchsize=${cfg.batchSize},`,
    `    save_as_csv=True,`,
    `    destfolder=os.environ["PD_OUTPUT"],`,
    "    # engine: " + cfg.engine + " | snapshot: " + ph(cfg.snapshot, "SNAPSHOT"),
    ")",
  )
  if (template.labelledVideo) {
    lines.push(
      "",
      "deeplabcut.create_labeled_video(",
      `    "${ph(cfg.dlcConfigPath, "DLC_CONFIG_PATH")}",`,
      `    [os.environ["PD_INPUT"]],`,
      `    destfolder=os.environ["PD_OUTPUT"],`,
      `    pcutoff=float(os.environ["PD_LIKELIHOOD"]),`,
      ")",
    )
  }
  lines.push("PY", "", `echo "[pd] Inference complete"`)
  return lines.join("\n")
}

export interface ValidationIssue {
  field: keyof InferenceConfig | "script"
  message: string
  severity: "error" | "warning"
}

export function validateConfig(cfg: InferenceConfig, template: SlurmTemplate, script: string): ValidationIssue[] {
  const issues: ValidationIssue[] = []
  for (const key of template.requiredParams) {
    const value = cfg[key]
    if (typeof value === "string" && !value.trim()) {
      issues.push({ field: key, message: `${PARAM_LABELS[key] ?? key} is required by “${template.name}”.`, severity: "error" })
    }
  }
  for (const key of ["dlcConfigPath", "workDir", "inputPath", "outputDir"] as const) {
    if (cfg[key].trim() && !cfg[key].trim().startsWith("/"))
      issues.push({ field: key, message: `${PARAM_LABELS[key]} should be an absolute path on MASSIVE.`, severity: "error" })
  }
  if (!/^(\d+-)?\d{1,2}:\d{2}:\d{2}$/.test(cfg.wallTime))
    issues.push({ field: "wallTime", message: "Wall time must be HH:MM:SS or D-HH:MM:SS.", severity: "error" })
  if (cfg.batchSize < 1) issues.push({ field: "batchSize", message: "Batch size must be at least 1.", severity: "error" })
  if (cfg.likelihoodThreshold <= 0 || cfg.likelihoodThreshold >= 1)
    issues.push({ field: "likelihoodThreshold", message: "Likelihood threshold must be between 0 and 1.", severity: "error" })
  if (template.id !== "dlc-cpu" && cfg.gpuCount < 1)
    issues.push({ field: "gpuCount", message: "GPU templates need at least one GPU.", severity: "error" })
  if (cfg.email.trim() && !/^[^@\s]+@[^@\s]+\.[^@\s]+$/.test(cfg.email.trim()))
    issues.push({ field: "email", message: "Notification email is not a valid address.", severity: "error" })
  if (cfg.memoryGb > 256) issues.push({ field: "memoryGb", message: "Large memory requests may queue for longer.", severity: "warning" })
  if (!script.includes("#SBATCH")) issues.push({ field: "script", message: "Script contains no #SBATCH directives.", severity: "error" })
  if (!script.includes("analyze_videos")) issues.push({ field: "script", message: "Script does not call deeplabcut.analyze_videos.", severity: "warning" })
  if (/<[A-Z_]+>/.test(script)) issues.push({ field: "script", message: "Script still contains unfilled <PLACEHOLDER> values.", severity: "error" })
  return issues
}
